// bareValidator reports whether the builtin registers as a bare
// validator: a single parameter with a boolean result — a plain bool,
// a Validator, or an error alone, whose successful result is true. The
// evaluator wraps such a builtin at registration, so its kind is that
// of the value it validates rather than func.
func bareValidator(fn *types.Func) bool {
	sign := fn.Signature()
	if sign.Params().Len() != 1 {
		return false
	}
	result := sign.Results().At(0).Type()
	if result == typeError {
		return true
	}
	b, ok := result.Underlying().(*types.Basic)
	return ok && b.Kind() == types.Bool
}

// pathOSRequired lists the pkg/path builtins whose trailing OS
// parameter is required rather than optional with the "unix" default.
// It mirrors the hand-written pkg/path/pkg.go; drift between the two
// is caught by this directory's tests, which compare every sig
// attribute against the registered builtin's parameters.
var pathOSRequired = map[string]bool{
	"SplitList": true,
	"ToSlash":   true,
	"FromSlash": true,
}

// paramHasDefault reports whether a parameter carries a default when
// its function is called with fewer arguments.
func paramHasDefault(funcName string, param *types.Var) bool {
	return param.Type().String() == "cuelang.org/go/pkg/path.OS" &&
		!pathOSRequired[funcName]
}

// defParam returns the declaration of a function parameter for use in
// a signature. A plain named parameter is positional as well, so the
// name is the raw builtin slot's contract label and, through the attached
// function type, lets a labeled call select that slot. An unnamed Go parameter is
// rendered as its bare type. A parameter the builtin reads as a schema —
// typed pkg.Schema in Go, so deliberately accepting a non-concrete value —
// carries the @schema() attribute, which the definition files declare as
// well.
func defParam(fn *types.Func, param *types.Var, precise bool) string {
	name := param.Name()
	typ := cueKindType(param.Type())
	if precise {
		typ = cueType(param.Type())
		if refined := nativeParams[nativeName(fn)][name]; refined != "" {
			typ = refined
		}
	}
	switch param.Type().String() {
	case "cuelang.org/go/internal/pkg.Schema":
		typ += " @schema()"
	case "cuelang.org/go/pkg/path.OS":
		name = "os"
		if paramHasDefault(fn.Name(), param) {
			// A parameter default is declared with "=" after the
			// constraint; a default mark in the constraint is rejected.
			typ += ` = "unix"`
		}
	}
	if name == "" {
		return typ
	}
	return fmt.Sprintf("%s: %s", name, typ)
}

// cueResultType provides CUE syntax describing the value a builtin
// produces for the given Go result type. It differs from a parameter's
// type in two places.
//
// A Go []byte is bytes|string as an argument, which the builtin
// converts, but always bytes as a result: nothing converts it back.
//
// A Go result of error alone reports validation success as true.
// Non-nil errors remain failures rather than successful false results.
func cueResultType(typ types.Type) string {
	switch {
	case typ == typeError:
		return "true"
	case isByteSlice(typ):
		return "bytes"
	}
	switch t := typ.(type) {
	case *types.Basic:
		// Native integer results cannot exceed their Go representation.
		// Inputs keep the logical CUE int domain: representation failures
		// remain ordinary partial-call failures at the native boundary.
		width := 0
		switch t.Kind() {
		case types.Int8, types.Uint8:
			width = 8
		case types.Int16, types.Uint16:
			width = 16
		case types.Int32, types.Uint32:
			width = 32
		case types.Int, types.Int64, types.Uint, types.Uint64, types.Uintptr:
			width = 64
		}
		if width != 0 {
			max := new(big.Int).Lsh(big.NewInt(1), uint(width))
			if t.Info()&types.IsUnsigned != 0 {
				return "int & >=0 & <=" + max.Sub(max, big.NewInt(1)).String()
			}
			max.Rsh(max, 1)
			min := new(big.Int).Neg(max)
			return "int & >=" + min.String() + " & <=" + max.Sub(max, big.NewInt(1)).String()
		}
	case *types.Slice:
		return cueListType(cueResultType(t.Elem()))
	case *types.Map:
		return "{[string]: " + cueResultType(t.Elem()) + "}"
	}
	switch typ.String() {
	case "*cuelang.org/go/pkg/time.Parts", "*cuelang.org/go/pkg/net.ParsedCIDR":
		record := typ.(*types.Pointer).Elem().Underlying().(*types.Struct)
		var fields []string
		for i := range record.NumFields() {
			field := record.Field(i)
			if !field.Exported() {
				continue
			}
			tag := reflect.StructTag(record.Tag(i)).Get("json")
			name, options, _ := strings.Cut(tag, ",")
			if name == "-" {
				continue
			}
			if name == "" {
				name = field.Name()
			}
			presence := ""
			if slices.Contains(strings.Split(options, ","), "omitempty") {
				presence = "?"
			}
			fields = append(fields, fmt.Sprintf("%q%s: %s", name, presence, cueResultType(field.Type())))
		}
		return "{" + strings.Join(fields, ", ") + "}"
	}
	return cueType(typ)
}

func cueListType(element string) string {
	if element == "_" {
		return "[...]"
	}
	return "[..." + element + "]"
}

// isByteSlice reports whether typ is a Go []byte.
func isByteSlice(typ types.Type) bool {
	slice, ok := typ.(*types.Slice)
	return ok && slice.Elem() == typeByte
}

// cueKindType describes the kind accepted for a native Go parameter.
// cueType additionally retains container element types for checking.
func cueKindType(typ types.Type) string {
	switch typ := typ.(type) {
	case *types.Slice:
		if typ.Elem() == typeByte {
			return "bytes|string"
		}
		return "[...]"
	case *types.Map:
		return "{...}"
	case *types.Basic:
		if typ.Info()&types.IsInteger != 0 {
			return "int"
		}
		if typ.Kind() == types.Float64 {
			return "number"
		}
		return typ.String() // "bool" and "string" are CUE types too
	}
	switch typ.String() {
	case "error":
		return "_|_"
	case validatorType:
		return "bool"
	case "io.Reader":
		return "bytes|string"
	case "cuelang.org/go/internal/pkg.Struct":
		return "{...}"
	case "cuelang.org/go/internal/pkg.List":
		return "[...]"
	case "*math/big.Int":
		return "int"
	case "*cuelang.org/go/internal.Decimal", "*math/big.Float":
		return "number"
	case "cuelang.org/go/cue.Value",
		"cuelang.org/go/cue/ast.Expr",
		"cuelang.org/go/internal/pkg.Schema":
		return "_"
	case "cuelang.org/go/pkg/path.OS":
		return "string"

	// Some builtin functions return custom types, like [cuelang.org/go/pkg/time.Split].
	case "*cuelang.org/go/pkg/time.Parts":
		return "{...}"
	case "*cuelang.org/go/pkg/net.ParsedCIDR":
		return "{...}"
	}
	log.Fatal("cueType: unhandled Go type ", typ.String())
	return ""
}

// Keep runtime call constraints at their existing kind granularity. The
// precise signature is evidence for checking, not a source of argument values.
func cueKindResultType(typ types.Type) string {
	if typ == typeError {
		return "bool"
	}
	if isByteSlice(typ) {
		return "bytes"
	}
	return cueKindType(typ)
}

func cueType(typ types.Type) string {
	if t, ok := typ.(*types.Slice); ok && !isByteSlice(typ) {
		return cueListType(cueType(t.Elem()))
	}
	return cueKindType(typ)
}
