// gen.go generates the pkg.go files inside the packages under the pkg
// directory. The pkg.cue definition files alongside them are
// maintained by hand; their consistency with the registered builtins
// is checked by the tests of the pkg package.
//
// Be sure to also update an entry in pkg/pkg.go, if so desired.
